// ---------- domain badges
const STATUS_CLASS: Record<ApplicationStatus, string> = { saved: '', preparing: 'badge-brand', applied: 'badge-brand', interview: 'badge-good', offer: 'badge-good', rejected: 'badge-bad', withdrawn: '' };
export function StatusBadge({ status }: { status: ApplicationStatus }) {
  return <span className={`badge ${STATUS_CLASS[status]}`}>{status[0].toUpperCase() + status.slice(1)}</span>;
}

const PROV: Record<Provenance, [string, string, string]> = {
  fact: ['badge-good', 'Fact', 'Directly supported by your resume'],
  inference: ['badge-warn', 'Inferred — verify', 'Inferred from the same role or project; please confirm it is accurate'],
  suggestion: ['badge-brand', 'Suggestion', 'Needs information only you have'],
  missing: ['badge-bad', 'Missing', 'Requested by the job but not in your resume'],
  user_confirmed: ['badge-good', 'Confirmed by you', 'You confirmed this'],
};
export function ProvenanceBadge({ p }: { p: Provenance }) {
  const [cls, label, title] = PROV[p];
  return (
    <span className={`badge ${cls}`} title={title}>
      {label}
    </span>
  );
}

export function scoreClass(n: number) {
  return n >= 75 ? 'badge-good' : n >= 55 ? 'badge-warn' : 'badge-bad';
}
export function ScorePill({ value }: { value: number | null | undefined }) {
  if (value == null) return <span className="muted">—</span>;
  return <span className={`badge ${scoreClass(value)}`}>{value}%</span>;
}

export function ScoreRing({ value, label }: { value: number; label: string }) {
  return (
    <div className="score-ring" style={{ ['--p' as string]: value }} role="img" aria-label={`${label}: ${value}%`}>
      <span>{value}%</span>
    </div>
  );
}
