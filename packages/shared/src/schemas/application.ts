export const SavedAnswerSourceSchema = z.enum(['user', 'learned', 'imported', 'profile']);
export type SavedAnswerSource = z.infer<typeof SavedAnswerSourceSchema>;

export const SavedAnswerSchema = z.object({
  id: z.string(),
  questionKey: z.string(),
  rawQuestion: z.string(),
  normalizedQuestion: z.string(),
  answer: z.string(),
  source: SavedAnswerSourceSchema,
  confidence: z.number(),
  useCount: z.number().int().default(0),
  sensitive: z.boolean().default(false),
  updatedAt: z.string(),
  createdAt: z.string(),
});
export type SavedAnswer = z.infer<typeof SavedAnswerSchema>;
